#!/usr/bin/env node
// Import PyLabRobot's labware library at a pinned commit (issue #55).
//
// PyLabRobot defines labware, carriers, adapters, modules and decks as Python
// factory functions, not data files, so the only faithful way to use them is
// to run them. This script does that in a throwaway virtual environment
// (uv) with PyLabRobot installed from the exact commit, runs
// scripts/plr_labware_export.py there, and writes the result as plain data to
// content/pylabrobot-labware.json. The site never ships or runs PyLabRobot.
//
// Usage: node scripts/labware-from-pylabrobot.mjs --commit <40-char SHA> --retrieved-at YYYY-MM-DD [--output path]
// Requires uv (https://docs.astral.sh/uv/) and network access to GitHub.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const args = process.argv.slice(2);
const opts = {};
for (let i = 0; i < args.length; i += 2) {
  if (!['--commit', '--retrieved-at', '--output'].includes(args[i]) || !args[i + 1]) throw Error('Usage: node scripts/labware-from-pylabrobot.mjs --commit <40-character SHA> --retrieved-at YYYY-MM-DD [--output path]');
  opts[args[i]] = args[i + 1];
}
const commit = opts['--commit'], retrievedAt = opts['--retrieved-at'];
if (!/^[0-9a-f]{40}$/.test(commit || '')) throw Error('An explicit immutable --commit SHA is required; main is not accepted.');
if (!/^\d{4}-\d{2}-\d{2}$/.test(retrievedAt || '')) throw Error('Explicit --retrieved-at date is required.');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = opts['--output'] ? resolve(opts['--output']) : join(root, 'content/pylabrobot-labware.json');
const exporter = join(root, 'scripts/plr_labware_export.py');
const work = mkdtempSync(join(tmpdir(), 'plr-labware-'));
const run = (cmd, a) => execFileSync(cmd, a, {cwd: work, stdio: ['ignore', 'pipe', 'inherit'], timeout: 600000}).toString();
try {
  run('uv', ['venv', '-q', '--python', '3.12', 'venv']);
  run('uv', ['pip', 'install', '-q', '--python', 'venv/bin/python', `pylabrobot @ git+https://github.com/PyLabRobot/pylabrobot.git@${commit}`]);
  const licence = run('venv/bin/python', ['-I', '-c', 'import importlib.metadata as m; d=m.distribution("pylabrobot"); print(d.metadata.get("License") or ""); print(d.version)']);
  const raw = join(work, 'export.json');
  process.stdout.write(run('venv/bin/python', ['-I', exporter, raw]));
  const bytes = readFileSync(raw);
  const data = JSON.parse(bytes);
  if (!data.count || data.count < 100) throw Error(`Only ${data.count} resources exported; refusing to replace the library.`);
  const out = {
    about: 'PyLabRobot resource library (labware, carriers, adapters, modules, decks) exported at a pinned commit by scripts/labware-from-pylabrobot.mjs. Geometry and well volumes are PyLabRobot definitions; they describe what PyLabRobot models, not manufacturer-verified compatibility. Refresh by bumping the commit (see .github/workflows/pylabrobot-update.yml).',
    provenance: {upstream: 'https://github.com/PyLabRobot/pylabrobot', commit, retrievedAt, license: 'MIT', packageMetadata: licence.trim().split('\n'), sourceUrl: `https://github.com/PyLabRobot/pylabrobot/tree/${commit}/pylabrobot/resources`, exportSha256: createHash('sha256').update(bytes).digest('hex'), importCommand: `node scripts/labware-from-pylabrobot.mjs --commit ${commit} --retrieved-at ${retrievedAt}`},
    ...data,
  };
  writeFileSync(output, JSON.stringify(out, null, 1) + '\n');
  if (!opts['--output']) {
    const file = join(root, 'THIRD_PARTY_NOTICES.md');
    let current = '# Third-party notices\n';
    try { current = readFileSync(file, 'utf8'); } catch {}
    const block = `<!-- labware:start -->\n## PyLabRobot resource library\n\nSource: ${out.provenance.sourceUrl}\n\nCommit: ${commit}. Retrieved: ${retrievedAt}. Export SHA-256: ${out.provenance.exportSha256}.\n\ncontent/pylabrobot-labware.json is generated by running PyLabRobot's resource factories (MIT licence, same notice as above) in an isolated environment; no PyLabRobot code is shipped. Geometry and volumes describe PyLabRobot's models, not manufacturer-verified compatibility.\n<!-- labware:end -->\n`;
    const re = /<!-- labware:start -->[\s\S]*<!-- labware:end -->\n?/;
    writeFileSync(file, re.test(current) ? current.replace(re, block) : `${current.trimEnd()}\n\n${block}`);
  }
  console.log(JSON.stringify({commit, resources: data.count, failures: data.failures.length, output}));
} finally {
  rmSync(work, {recursive: true, force: true});
}
